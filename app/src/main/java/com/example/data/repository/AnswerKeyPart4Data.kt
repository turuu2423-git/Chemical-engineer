2. Бэлэн байдлын коэффициент (Availability): Availability = MTBF / (MTBF + MTTR).
3. Урьдчилан таамаглах vs Хуваарьт засвар: Төхөөрөмжийн бодит төлөв байдал, чичиргээ, тосны шинжилгээнд үндэслэх (Condition-based) vs Хуанлийн хугацаагаар хийх.
4. As-found утга: Засвар хийхээс өмнөх элэгдлийн бодит түвшин ба өнгөрсөн хугацааны аюулгүй байдлыг батлахад.
5. Like-for-like нотолгоо: Функциональ зориулалт, материал, ажлын хязгаар, холболтын хэмжээ, тохиргоо ба гэрчилгээ бүрэн ижил байх.
6. Давтагдах эвдрэлд: Засварын интервалыг ойртуулахаас гадна системийн RCA хийж дизайн ба процессын өөрчлөлтийг үнэлнэ.

[79 · GHS, SDS ба химийн аюулын мэдээлэл]:
1. Hazard vs Risk: Бодисын өөрийн дотоод аюултай чанар vs Бодит орчинд тухайн бодист өртөх магадлал ба үр дагаврын хослол.
2. SDS бүлгүүдийн тоо: Олон улсын GHS стандартын дагуу 16 үндсэн бүлэгтэй.
3. Шошгын үүрэг: Аюулын талаарх мэдээллийг хэрэглэгчид шуурхай, стандартын дагуу хүргэх.
4. Шошгогүй савтай бодис: Ашиглахыг хатуу хориглож, тусгаарлан, эрх бүхий удирдлагад мэдэгдэнэ.
5. Хувилбарын хяналт: Хүчин төгөлдөр SDS-ийн нэгдсэн бүртгэл хөтөлж, хуучирсан хувилбарыг архивлана.
6. Хамгаалах хэрэгслийн шатлал: PPE бол хамгийн доод түвшний хамгаалалт бөгөөд аюулыг арилгах, орлуулах, инженерийн ба захиргааны хяналтын дараа хэрэглэгдэнэ.

[80 · Химийн нийцэмж, segregation ба хадгалалтын систем]:
1. Нийцэмжийн эх сурвалжууд: SDS/TDS (Бүлэг 7, 10), Нийцэмжийн матриц, Нийлүүлэгчийн лавлагаа, Баталгаажсан туршилтын протокол, Хууль тогтоомж.
2. Хоёрдогч хамгаалалтын сав (Secondary containment): Асгаралт, алдагдал тархахаас сэргийлэх багтаамж (хамгийн том савны 110%).
3. Хоосон савны аюул: Үлдэгдэл химийн бодис, шатамхай/хорт уур ялгарах эрсдэл.
4. FEFO зарчим: First-Expire-First-Out (Хугацаа нь түрүүлж дуусахыг түрүүлж хэрэглэх).
5. Тодорхойгүй асгаралт: Талбайг тусгаарлаж, аюулгүй байдлын дохио өгч, ERP төлөвлөгөөгөөр шийднэ.
6. Агуулахын үзлэгийн талбарууд: Шошго/савлагааны бүрэн бүтэн байдал, гоожилт, температур/чийг, цэвэрлэгээ, бодисын зааглалт, галын хамгаалалт ба тооллого.

[81 · Монголын хууль, дүрэм, лиценз ба эрх бүхий ажиллагаа]:
1. Хууль зүйн шатлал: Хууль -> Засгийн газрын тогтоол/дүрэм -> Салбарын стандарт/лиценз -> Компанийн журам -> Талбайн ажил гүйцэтгэх зөвшөөрөл.
2. Хүчин төгөлдөр байдал: Legalinfo.mn албан ёсны эх сурвалж болон хуулийн хариуцагчийн хяналтаар баталгаажуулна.
3. Тусгай зөвшөөрлийн хугацаа дуусах үед: Холбогдох үйл ажиллагааг нэн даруй зогсоож, удирдлагад эскалаци хийнэ.
4. Нийцлийн бүртгэлийн талбарууд: Хуулийн шаардлага, хамрах хүрээ, нотлох баримт, хариуцах эзэн, хяналтын давтамж, хувилбар.
5. Компанийн журам хуулиас хатуу байж болох уу: Болно (Хуулийн шаардлага бол доод хязгаар бөгөөд компани түүнээс илүү өндөр стандарт тогтоож болно).
6. Химичийн хуулийн хариуцлага: Эрх олгогдсон хүрээнд ажиллах, үнэн зөв нотолгоо гаргах, аюулыг эскалаци хийх, эрх мэдлээс хэтэрсэн үйлдэл хийхгүй байх.

[82 · Тээвэр, хамгаалалт, нөөц ба chain of custody]:
1. Chain of custody: Хэн, хэзээ, хаана, ямар материалыг хүлээлцсэн тухай баримтжуулсан мөрдөх хэлхээ.
2. Лацны дугаар зөрөх үед: Тээврийн хэрэгслийг нээхгүйгээр битүүмжилж, харуул хамгаалалт болон удирдлагад мэдэгдэн шалгалт эхлүүлнэ.
3. Тээврийн баланс: Opening + Received = Issued + Returned + Disposed.
4. Зөрүү (Discrepancy): Бодит хэмжсэн тоо - Баримтаар хүлээгдэж буй тоо.
5. Хоосон савлагааны төлөв: Угааж аюулгүй болгосон, үзлэг хийсэн, дүрэм журмын дагуу сертификат олгогдсон байх.
6. Тээврийн бүртгэлийн талбарууд: Давтагдашгүй ID, тоо хэмжээ/нэгж, лацны дугаар, хүлээлцсэн талууд, огноо-цаг/байршил, материалын нөхцөл байдал.

[83 · HAZID, JSA, HAZOP ба LOPA-ийн зөв хэрэглээ]:
1. JSA vs HAZOP: Тодорхой нэг ажлын даалгаврын аюулын шинжилгээ vs Процессын шугам хоолойн параметрүүдийн хазайлтыг шинжлэх арга.
2. LOPA-ийн үүрэг: Аюулын хувилбар бүрд бие даасан хамгаалалтын давхаргуудын (IPL) эрсдэл бууруулах найдвартай байдлыг тоон утгаар үнэлэх.
3. IPL-ийн бие даасан байдал: Нийтлэг шалтгааны гэмтэлгүй (No common cause failure) бөгөөд бусад системээс хараат бус ажиллах чадвар.
4. Үлдэгдэл эрсдэл (Residual risk): Бүх хяналт ба хамгаалалтын арга хэмжээг авсны дараа үлдэх эрсдэлийн бодит түвшин.
5. Ажлын цар хүрээ өөрчлөгдөхөд: MOC үүсгэж, аюулын үнэлгээг шинэчлэн баталгаажуулна.
6. Арга хэмжээг хаах нотолгоо: Тоног төхөөрөмж суурилагдсан, туршигдсан, баримтжуулагдсан, эрх бүхий хүлээн авалт хийгдсэн, журам ба сургалт шинэчлэгдсэн байх.

[84 · MOC, PSSR, permit-to-work ба ажлын өмнөх баталгаа]:
1. MOC үе шатууд: Тодорхойлох -> Эрсдэл үнэлэх/хянах -> Батлах -> Хэрэгжүүлэх -> Турших/PSSR -> Хаах.
2. PSSR (Ажил эхлэхийн өмнөх аюулгүй байдлын үзлэг): Шинэ эсвэл өөрчлөгдсөн системийг ажиллуулахаас өмнө бүх аюулгүй байдлын шаардлага хангагдсаныг газар дээр нь шалгах.
3. Зөвшөөрлийн хуудас (PTW): Тодорхой даалгавар, тодорхой байршил, тодорхой цаг хугацаа ба тусгайлан заасан хяналтын арга хэмжээнд хүчинтэй.
4. Like-for-like өөрчлөлтийн нотолгоо: Функциональ зориулалт, материал, тохиргоо, аюулгүйн үзүүлэлт ба гэрчилгээний бүрэн дүйцэл.
5. Түр өөрчлөлтийн хугацаа дуусахад: Системийг анхны хэвийн төлөвт нь буцаан оруулах эсвэл албан ёсоор хугацааг сунгах шийдвэр гаргах.
6. Firmware шинэчлэл: MOC өөрчлөлтийн хяналтын дагуу нөлөөллийн шинжилгээ хийж баталгаажуулна.

[85 · Хөдөлмөрийн эрүүл ахуй, өртөлт ба PPE]:
1. TWA vs STEL: 8 цагийн ажлын ээлжийн жигнэсэн дундаж өртөлт vs 15 минутын богино хугацааны дээд өртөлтийн хязгаар.
2. Аюулыг хянах шатлал: Арилгах (Elimination) -> Орлуулах (Substitution) -> Инженерийн хяналт -> Захиргааны хяналт -> Хамгаалах хэрэгсэл (PPE).
3. Үнэрлэх мэдрэмжийн хязгаар: Үнэрлэх босго хувь хүн бүрд өөр, дасах үзэгдэл явагддаг, зарим хорт хий огт үнэргүй байдаг тул үнэрээр аюулыг үнэлэхгүй.
4. Багны Fit test: Сонгосон амьсгалын баг ажилтны нүүрэнд бүрэн битүүмжлэгдэж байгааг шалгах сорил.
5. Агаарын дээжийн эзлэхүүн: V = Урсгалын хурд * Хугацаа.
6. Өндөр өртөлт илрэхэд: Ажилтныг тусгаарлан хамгаалах, удирдлагад мэдэгдэх, эх үүсвэрийн хяналт хийх, эмнэлгийн үзлэгт хамруулах.

[86 · Асгаралт, алдагдал, хаягдал ба байгаль орчны хамгаалалт]:
1. Эх үүсвэр—Замнал—Хүлээн авагч (Source-Pathway-Receptor): Бохирдлын үүсгүүр, түүний хөрс/ус/агаараар дамжих зам, бохирдолд өртөх хүн/байгаль орчин.
2. Тодорхойгүй асгаралт: Дохио өгөх, тусгаарлах, SDS-ээр таних, ERP төлөвлөгөө дагах; дур мэдэн химийн туршилт хийхгүй.
3. Хаягдлын тодорхойлолт: Хууль эрх зүй, химийн найрлага ба физик аюулын статусыг баримтжуулах.
4. Манифест (Manifest): Аюултай хаягдлын гарал үүсэл, тоо хэмжээ, тээвэрлэгч ба эцсийн устгах цэгийн хяналтын баримт.
5. Шингэлэх (Dilution) нь шийдэл биш: Нийт массын хорогдол гарахгүй, зөвхөн аюулын орон зайн тархалтыг нэмэгдүүлнэ.
6. Талбайг цэвэрлэж хаах нотолгоо: Батлагдсан аргаар цэвэрлэх, хөрс/усны лабораторийн хяналтын дээж авах, эрх бүхий байгууллагын актаар баталгаажуулах.

[87 · Гал, thermal event, misfire ба онцгой байдлын командлал]:
1. Онцгой байдлын командлагч (Incident Commander): Онцгой нөхцөл байдлын үед талбайн бүх үйл ажиллагааг нэгдсэн удирдлага, зохицуулалтаар хангах эрх бүхий албан тушаалтан.
2. Нарийн тооллого байхгүй үед: Хамгийн сүүлийн баталгаажсан үлдэгдэл + шилжүүлгийн бүртгэлүүд дээр суурилсан бодит мужийг тайлагнах.
3. Misfire (Дутуу тэсрэлт) үед химичийн үүрэг: Бүсээс холдон тусгаарлалт тогтооход туслах, мэдээллийг холбогдох албанд дамжуулах, капсуль/дэлбэрэх хэрэгсэлд гар хүрэхгүй байх.
4. Онцгой байдлын багц (Emergency pack): Бодисын SDS, талбайн схем зураг, материалын үлдэгдэл, холбоо барих утаснууд, инженерийн шугам сүлжээ ба ус зайлуулах сувгийн байршил.
5. Химич онцгой байдлын багт өгөх мэдээлэл: Бодисын нэршил, физик-химийн шинж чанар, нийцэмж, агуулах дахь бодит тоо хэмжээ.
6. Тактикийн эх сурвалж: Батлагдсан ERP төлөвлөгөө, мэргэжлийн аврах албаны зааварчилгаа.

[88 · Reactive ground ба thermal runaway-ийн эрсдэлийн удирдлага]:
1. Дулааны хяналтгүй урвал (Thermal runaway): Урвалын дулаан ялгаралт нь орчинд дулаан алдах хурдаас давж, температур өсөх тусам урвал улам хурдсах гинжин процесс.
2. Аррениусын тэгшитгэлийн хувьсагчид: k = A * exp(-E_a / (R * T)) -> A (Давтамжийн хүчин зүйл), E_a (Идэвхжлийг энерги), R (Хийн тогтмол), T (Температур, K).
3. A/V масштабын эффект: Том эзлэхүүнтэй саванд нэгж эзлэхүүнд ногдох гадаргуугийн дулаан алдагдал бага тул runaway үүсэх эрсдэл эрс өснө.
4. Урвал эхлэх температур (Onset temperature): Сорилтын арга, дээжийн масс, масштаб болон туршилтын нөхцөлөөс хамаарна.
5. Температур огцом хурдсах үед: Дохиолол өгч, ажиллагааг зогсоон (Hold), ERP төлөвлөгөөг идэвхжүүлнэ; таамгаар хугацаа тооцож ойртохгүй.
6. Screening records (Шалгалтын бүртгэл): Геологийн бүс, дээжийн гинжин хэлхээ, изотермик сорилтын протокол, бүтээгдэхүүний марк, үр дүн ба эрх бүхий зөвшөөрөл.

[89 · Human factors, fatigue, shift handover ба contractor control]:
1. Human Factors (Хүний хүчин зүйл): Хүн, ажлын даалгавар, тоног төхөөрөмж ба байгууллагын засаглалын хоорондын харилцан үйлчлэлийн шинжлэх ухаан.
2. Ядаргааны нөлөө: Анхаарал сарних, ой тогтоолт муудах, хариу үйлдэл удаашрах, эрсдэлийг буруу үнэлэх.
3. Closed-loop communication (Битүү гогцоот харилцаа): Мэдээлэл илгээх -> Хүлээн авагч давтан хэлэх -> Илгээгч зөв болохыг баталгаажуулах.
4. Ээлж хүлээлцэх бүртгэлийн талбарууд: Тоног төхөөрөмжийн бодит статус, аюул ба хяналт, хариуцах эзэн, хийгдэх ажлууд, хугацааны тамга.
5. Гүйцэтгэгчийн хяналт: Зөвхөн аюулгүй ажиллагааны зааварчилгаа өгөөд зогсохгүй, тухайн ажилд шаардагдах мэргэжлийн чадамжийн бодит нотолгоо ба эрхийг шалгана.
6. Давтагдсан алдаа гаргахад: Системийн шалтгааныг шинжилж, ажлын байрны дизайн болон инженерийн хамгаалалтыг сайжруулна.

[90 · Осол, near miss, notification ба мөрдөн шалгалт]:
1. Near Miss (Осол дөхсөн тохиолдол): Хүн бэртээгүй, эд хөрөнгийн хохирол учраагүй боловч осол гарах бодит боломж бүрдсэн байсан үйл явдал.
2. Ослын талбайн анхны тэргүүн дараалал: Хүний амь нас, аюулгүй байдлыг хангах (Life safety) ба ERP арга хэмжээ, дараа нь талбайн нотлох баримтыг хамгаалалтад авах.
3. Цагийн синхрончлол: Цагийн зөрүүг засварласан хуулбар гаргаж, анхдагч файлуудыг өөрчлөлтгүйгээр хадгална.
4. Нотлох баримтын бүртгэл (Evidence register): Баримтын ID, эх үүсвэр, эзэмшлийн гинжин хэлхээ, цаг хугацаа, бүрэн бүтэн байдал, хадгалах байршил, хандах эрх.
5. Гэрчүүдийн мэдүүлэг зөрөхөд: Баримт өгөгдлүүдтэй тулган шалгаж (Triangulate) шинжилнэ; олонхын саналаар шийдэхгүй.
6. Үйл ажиллагааг дахин эхлүүлэх (Restart authority): Тодорхойлсон бүх арга хэмжээ хэрэгжиж, PSSR хийгдсэний дараа зөвхөн эрх бүхий удирдлага болон төрийн хяналтын шийдвэрээр зөвшөөрнө.

[91 · Аудит, баримт бичгийн хяналт, ёс зүй ба тасралтгүй хөгжил]:
1. Аудитын зорилго: Системийн тохирол (Conformity) ба бодит үр ашигтай байдлыг (Effectiveness) бие даан шалгах.
2. Аудитын үл тохирлын элементүүд: Стандартын шаардлага (Requirement), Бодит нотолгоо (Objective evidence), Үүссэн зөрүү ба эрсдэл (Gap/Risk).
3. Баримт бичгийн амьдралын мөчлөг: Төсөл боловсруулах -> Хянах -> Батлах -> Мөрдүүлэх -> Шинэчлэх -> Архивлаж хүчингүй болгох.
