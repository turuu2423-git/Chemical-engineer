5. Масс-эзлэхүүний хөрвүүлэлт: Нягт ба тухайн үеийн температурын төлөв шаардлагатай.
6. Тооцооны маягтын шалгалт: Сөрөг бус/хязгаартай тоо, нэгж, дараалал, rollover/reset-ийн бүрэн байдал, бие даасан тулгалт.

[53 · Бодит компонентын харьцаа ба хэмжилтийн хоёр арга]:
