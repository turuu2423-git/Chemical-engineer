2. Сорилтын тусгай үр дүн (Test-specific result): Зөвхөн тухайн багаж, стандарт журам, төгсгөлийн цэгт (endpoint) хүчинтэй.
3. Pass/Fail-ийг нэгтгэж нэг оноо болгохгүй: Аюулгүйн механизм ба өдөөх энерги нь физикийн хувьд тэс өөр тул.
4. Дээж бэлтгэл (Sample conditioning): Дээжийн температур, чийг, насжилтыг давтагдахуйц стандарт төлөвт оруулах.
5. Стандартаас хазайх: Хазайлт (Deviation), түүний нөлөөлөл, албан ёсны зөвшөөрөл ба үр дүнгийн хүчинтэй хүрээг тодорхой бичнэ.
6. Нэр томьёоны бүртгэл: Англи нэр, Монгол оноолт, тодорхойлолт, эх сурвалж, хэрэглээний хүрээ ба төөрөгдлийн сануулга.

[50 · Талбайн ажлын урсгал ба эрхийн хил]:
