2. Жишиг суурь (Reference basis): 100% буюу 1.0 утга ямар стандарт бодист (ихэвчлэн ANFO, ρ=0.85 г/см³) харгалзахыг тогтооно.
3. RBS хөрвүүлэх томьёо: RBS ≈ RWS * (ρ_product / ρ_reference).
4. Нягт дутуу үед: Тооцоо хийх боломжгүйг илэрхийлж, нягтыг дутуу өгөгдлөөр бүртгэнэ.
5. Энергийн индекс талбайн бодит үр дүн биш: Энергийн хуваарилалт (shock vs gas), чулуулгийн шинж, геометр, хугацаа ба холболт нөлөөлнө.
6. Нийлүүлэгчдийн өгөгдлийг жишихээс өмнө: Жишиг стандарт, хэмжих нэгж, нягтын төлөв, тооцооны термодинамик код ба аргын хувилбарыг нэг мөр болгоно.

[49 · Мэдрэмжийн нэр томьёо, сорил ба зохистой тайлбар]:
