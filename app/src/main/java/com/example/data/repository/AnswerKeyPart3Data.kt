2. Hold point: Эрх бүхий хяналт шалгалт хийж, албан ёсны зөвшөөрөл олгох хүртэл ажлыг түр зогсоох цэг.
3. Хувилбар зөрөхөд: Hold хийж, батлагдсан хүчин төгөлдөр эх хувийг баталгаажуулна.
4. Химичийн эрхийн хил: Бүтээгдэхүүний чанар, хэмжилтийн нотолгоо гаргах; тэсэлгээний талбайн дизайны эрх биш.
5. Handover (Ээлж хүлээлцэх): Бодит төлөв байдал, материалын үлдэгдэл тоо, гарсан хазайлт, аюул занал, хариуцах эзэн ба хийх ажлууд.
6. Бүртгэл дутуу үед: Missing data/deviation гэж тэмдэглэн, эх сурвалж/цагийг зааж нөхөн сэргээх төлөвлөгөө гаргана; тааж бөглөхгүй.

