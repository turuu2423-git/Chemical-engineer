2. Таг (Tag) дугаарын үүрэг: Хэмжих хэрэгсэл, төхөөрөмжийн нэг бүрчлэн мөрдөх давтагдашгүй код.
3. Бодит байдал зурагтай зөрөхөд: Баримтжуулж, холбогдох аюулд Hold хийн, MOC-оор зургийг шинэчилнэ.
